import Foundation
import CryptoKit
import Darwin

enum InstallError: Error { case invalidConfiguration, unsafePath, writeFailure, configurationChanged, busy }

enum NativeHookInstaller {
    private static let codexEvents = ["SessionStart", "SessionEnd", "UserPromptSubmit", "PreToolUse", "PermissionRequest", "PostToolUse", "SubagentStart", "SubagentStop", "Stop", "Interrupt"]
    private static let antigravityEvents = ["PreInvocation", "PostToolUse", "Stop"]

    static func shellQuote(_ path: String) -> String {
        "'" + path.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    // Parse the simple shell syntax generated by AgentIsland. Refuse shell
    // substitutions/operators, so arbitrary user hooks are never mistaken for ours.
    static func shellWords(_ command: String) -> [String]? {
        enum Quote { case none, single, double }
        var result: [String] = [], current = "", quote = Quote.none, escaped = false, started = false
        for char in command {
            if escaped { current.append(char); escaped = false; started = true; continue }
            switch quote {
            case .single:
                if char == "'" { quote = .none } else { current.append(char) }
            case .double:
                if char == "\"" { quote = .none }
                else if char == "\\" { escaped = true }
                else if "`$".contains(char) { return nil }
                else { current.append(char) }
            case .none:
                if char == "'" { quote = .single; started = true }
                else if char == "\"" { quote = .double; started = true }
                else if char == "\\" { escaped = true; started = true }
                else if char.isWhitespace {
                    if started { result.append(current); current = ""; started = false }
                } else if "`$;|&<>\n\r".contains(char) { return nil }
                else { current.append(char); started = true }
            }
        }
        guard quote == .none, !escaped else { return nil }
        if started { result.append(current) }
        return result
    }

    static func isOwn(_ command: String, source: String) -> Bool {
        guard var args = shellWords(command), !args.isEmpty else { return false }
        var script = args.removeFirst()
        if script == "/usr/bin/python3" {
            guard !args.isEmpty else { return false }
            script = args.removeFirst()
            guard URL(fileURLWithPath: script).lastPathComponent == "record_hook.py" else { return false }
        } else if URL(fileURLWithPath: script).lastPathComponent != "AgentIslandHook" { return false }
        let parts = URL(fileURLWithPath: script).standardizedFileURL.pathComponents
        let legacyRoot = parts.count >= 3 && ["scripts", "hooks"].contains(parts[parts.count - 2]) && ["AiKeyboardLight", "AgentIsland", "AiStatusBar"].contains(parts[parts.count - 3])
        let nativeRoot = parts.count >= 5 && parts[parts.count - 3] == "native" && parts[parts.count - 4] == "hooks" && parts[parts.count - 5] == "AgentIsland"
        guard legacyRoot || nativeRoot, args.count >= 2, args[0] == "--source", args[1] == source else { return false }
        if source == "codex" { return args.count == 2 }
        return args.count == 4 && args[2] == "--event" && antigravityEvents.contains(args[3])
    }

    static func stripOwn(_ entries: [Any], source: String) -> [Any] {
        entries.compactMap { entry in
            guard var group = entry as? [String: Any] else { return entry }
            if let children = group["hooks"] as? [Any] {
                let remaining = children.filter { child in
                    guard let item = child as? [String: Any], let command = item["command"] as? String else { return true }
                    return !isOwn(command, source: source)
                }
                if remaining.isEmpty, !children.isEmpty,
                   Set(group.keys).isSubset(of: ["hooks", "matcher"]) { return nil }
                group["hooks"] = remaining
                return group
            }
            if let command = group["command"] as? String, isOwn(command, source: source) { return nil }
            return group
        }
    }

    static func removeOwn(_ config: [String: Any], source: String) throws -> ([String: Any], Bool) {
        guard ["codex", "antigravity"].contains(source) else { throw InstallError.invalidConfiguration }
        var output = config, changed = false
        let namespaces = source == "codex" ? ["hooks"] : ["aikeyboardlight", "agentisland"]
        for namespace in namespaces {
            guard output[namespace] == nil || output[namespace] is [String: Any] else { throw InstallError.invalidConfiguration }
            guard var hooks = output[namespace] as? [String: Any] else { continue }
            for (event, value) in hooks {
                guard let entries = value as? [Any] else { continue }
                let remaining = stripOwn(entries, source: source)
                let before = try JSONSerialization.data(withJSONObject: entries, options: [.sortedKeys])
                let after = try JSONSerialization.data(withJSONObject: remaining, options: [.sortedKeys])
                if before != after {
                    changed = true
                    if remaining.isEmpty { hooks.removeValue(forKey: event) } else { hooks[event] = remaining }
                }
            }
            if hooks.isEmpty && source == "antigravity" { output.removeValue(forKey: namespace) }
            else { output[namespace] = hooks }
        }
        return (output, changed)
    }

    static func uninstall(source: String, configuration: URL) throws -> Bool {
        try withConfigurationLock(configuration) {
            try uninstallLocked(source: source, configuration: configuration)
        }
    }

    private static func uninstallLocked(source: String, configuration: URL) throws -> Bool {
        var metadata = stat()
        guard lstat(configuration.path, &metadata) == 0,
              metadata.st_mode & mode_t(S_IFMT) == mode_t(S_IFREG) else { throw InstallError.unsafePath }
        let original = try Data(contentsOf: configuration)
        guard original.count <= 4 * 1024 * 1024,
              let json = try JSONSerialization.jsonObject(with: original) as? [String: Any] else { throw InstallError.invalidConfiguration }
        let (updated, changed) = try removeOwn(json, source: source)
        guard changed else { return false }
        let data = try JSONSerialization.data(withJSONObject: updated, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) + Data([10])
        let parent = configuration.deletingLastPathComponent()
        let backup = parent.appendingPathComponent(configuration.lastPathComponent + ".agentisland-backup-" + UUID().uuidString)
        try writeExclusive(original, to: backup)
        let temporary = parent.appendingPathComponent(".agentisland-" + UUID().uuidString)
        try writeExclusive(data, to: temporary)
        defer { try? FileManager.default.removeItem(at: temporary) }
        guard lstat(configuration.path, &metadata) == 0, metadata.st_mode & mode_t(S_IFMT) == mode_t(S_IFREG),
              try Data(contentsOf: configuration) == original else { throw InstallError.configurationChanged }
        guard rename(temporary.path, configuration.path) == 0 else { throw InstallError.writeFailure }
        // Do not delete versioned binaries: another configuration may reference them.
        return true
    }

    static func merge(_ config: [String: Any], source: String, helper: String) throws -> [String: Any] {
        guard ["codex", "antigravity"].contains(source) else { throw InstallError.invalidConfiguration }
        var output = config
        let prefix = shellQuote(helper) + " --source " + source
        if source == "codex" {
            guard output["hooks"] == nil || output["hooks"] is [String: Any] else { throw InstallError.invalidConfiguration }
            var hooks = output["hooks"] as? [String: Any] ?? [:]
            for event in codexEvents {
                guard hooks[event] == nil || hooks[event] is [Any] else { throw InstallError.invalidConfiguration }
                var entries = stripOwn(hooks[event] as? [Any] ?? [], source: source)
                entries.append(["hooks": [["type": "command", "command": prefix, "timeout": 1]]])
                hooks[event] = entries
            }
            output["hooks"] = hooks
        } else {
            for namespace in ["aikeyboardlight", "agentisland"] {
                guard output[namespace] == nil || output[namespace] is [String: Any] else { throw InstallError.invalidConfiguration }
                guard var hooks = output[namespace] as? [String: Any] else { continue }
                for (event, value) in hooks {
                    guard let entries = value as? [Any] else { continue }
                    let remaining = stripOwn(entries, source: source)
                    if remaining.isEmpty { hooks.removeValue(forKey: event) } else { hooks[event] = remaining }
                }
                if hooks.isEmpty { output.removeValue(forKey: namespace) } else { output[namespace] = hooks }
            }
            var hooks = output["agentisland"] as? [String: Any] ?? [:]
            for event in antigravityEvents {
                guard hooks[event] == nil || hooks[event] is [Any] else { throw InstallError.invalidConfiguration }
                var entries = hooks[event] as? [Any] ?? []
                let command: [String: Any] = ["type": "command", "command": prefix + " --event " + event, "timeout": 1]
                if event == "PostToolUse" { entries.append(["matcher": "*", "hooks": [command]]) }
                else { entries.append(command) }
                hooks[event] = entries
            }
            output["agentisland"] = hooks
        }
        return output
    }

    static func install(source: String, configuration: URL, recorderDirectory: URL, executable: URL) throws {
        try withConfigurationLock(configuration) {
            try installLocked(source: source, configuration: configuration, recorderDirectory: recorderDirectory, executable: executable)
        }
    }

    private static func installLocked(source: String, configuration: URL, recorderDirectory: URL, executable: URL) throws {
        let fm = FileManager.default
        var metadata = stat()
        let exists = lstat(configuration.path, &metadata) == 0
        if exists && metadata.st_mode & mode_t(S_IFMT) != mode_t(S_IFREG) { throw InstallError.unsafePath }
        let original = exists ? try Data(contentsOf: configuration) : nil
        guard (original?.count ?? 0) <= 4 * 1024 * 1024 else { throw InstallError.invalidConfiguration }
        let json: [String: Any]
        if let original {
            guard let object = try JSONSerialization.jsonObject(with: original) as? [String: Any] else { throw InstallError.invalidConfiguration }
            json = object
        } else { json = [:] }
        let binary = try Data(contentsOf: executable)
        guard !binary.isEmpty else { throw InstallError.writeFailure }
        let hash = SHA256.hash(data: binary).map { String(format: "%02x", $0) }.joined()
        let versionedDirectory = recorderDirectory.appendingPathComponent("native/" + hash, isDirectory: true)
        let helper = versionedDirectory.appendingPathComponent("AgentIslandHook")
        let merged = try merge(json, source: source, helper: helper.path)
        let data = try JSONSerialization.data(withJSONObject: merged, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) + Data([10])
        try fm.createDirectory(at: versionedDirectory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        if lstat(helper.path, &metadata) == 0 {
            guard metadata.st_mode & mode_t(S_IFMT) == mode_t(S_IFREG),
                  metadata.st_uid == getuid(), metadata.st_mode & mode_t(S_IXUSR) != 0,
                  try Data(contentsOf: helper) == binary else { throw InstallError.unsafePath }
        } else {
            guard errno == ENOENT else { throw InstallError.unsafePath }
            try writeExclusive(binary, to: helper)
            guard chmod(helper.path, 0o700) == 0 else { throw InstallError.writeFailure }
        }
        try fm.createDirectory(at: configuration.deletingLastPathComponent(), withIntermediateDirectories: true)
        if let original {
            guard lstat(configuration.path, &metadata) == 0, metadata.st_mode & mode_t(S_IFMT) == mode_t(S_IFREG), try Data(contentsOf: configuration) == original else { throw InstallError.configurationChanged }
            let backup = configuration.deletingLastPathComponent().appendingPathComponent(configuration.lastPathComponent + ".agentisland-backup-" + UUID().uuidString)
            try writeExclusive(original, to: backup)
        } else if lstat(configuration.path, &metadata) == 0 { throw InstallError.configurationChanged }
        // Owner-only staging avoids leaking a private config during atomic replacement.
        let temporary = configuration.deletingLastPathComponent().appendingPathComponent(".agentisland-" + UUID().uuidString)
        try writeExclusive(data, to: temporary)
        defer { try? fm.removeItem(at: temporary) }
        if let original {
            guard lstat(configuration.path, &metadata) == 0, metadata.st_mode & mode_t(S_IFMT) == mode_t(S_IFREG), try Data(contentsOf: configuration) == original else { throw InstallError.configurationChanged }
        } else if lstat(configuration.path, &metadata) == 0 { throw InstallError.configurationChanged }
        guard rename(temporary.path, configuration.path) == 0 else { throw InstallError.writeFailure }
    }

    // Keep the lock file in place: deleting it lets concurrent processes lock
    // different inodes. This only coordinates AgentIsland installers; external
    // writers still require the unchanged-content check immediately before rename.
    private static func withConfigurationLock<T>(_ configuration: URL, _ body: () throws -> T) throws -> T {
        let parent = configuration.deletingLastPathComponent().standardizedFileURL.resolvingSymlinksInPath()
        try FileManager.default.createDirectory(at: parent, withIntermediateDirectories: true)
        let digest = SHA256.hash(data: Data(configuration.lastPathComponent.utf8)).map { String(format: "%02x", $0) }.joined()
        let path = parent.appendingPathComponent(".agentisland-lock-" + digest).path
        let fd = open(path, O_RDWR | O_CREAT | O_NOFOLLOW, mode_t(0o600))
        guard fd >= 0 else { throw InstallError.unsafePath }
        defer { close(fd) }
        var metadata = stat()
        guard fstat(fd, &metadata) == 0, metadata.st_mode & mode_t(S_IFMT) == mode_t(S_IFREG),
              metadata.st_uid == getuid(), metadata.st_mode & mode_t(0o077) == 0 else { throw InstallError.unsafePath }
        let deadline = ProcessInfo.processInfo.systemUptime + 2
        while flock(fd, LOCK_EX | LOCK_NB) != 0 {
            guard errno == EWOULDBLOCK || errno == EAGAIN || errno == EINTR else { throw InstallError.writeFailure }
            guard ProcessInfo.processInfo.systemUptime < deadline else { throw InstallError.busy }
            usleep(10_000)
        }
        defer { flock(fd, LOCK_UN) }
        return try body()
    }

    private static func writeExclusive(_ data: Data, to destination: URL) throws {
        let fd = open(destination.path, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW, mode_t(0o600))
        guard fd >= 0 else { throw InstallError.writeFailure }
        var good = true, offset = 0
        while offset < data.count {
            let n = data.withUnsafeBytes { Darwin.write(fd, $0.baseAddress!.advanced(by: offset), data.count - offset) }
            if n < 0 && errno == EINTR { continue }
            if n <= 0 { good = false; break }
            offset += n
        }
        if fsync(fd) != 0 { good = false }
        close(fd)
        if !good {
            try? FileManager.default.removeItem(at: destination)
            throw InstallError.writeFailure
        }
    }
}
